/** Writes docs/blog/topic-shelves-assignments.csv + counts in topic-shelves-mapping.md. */
import { readFileSync, writeFileSync } from "node:fs";
import { assignShelf, SHELF_DISPLAY_ORDER, SHELVES_BY_ID, SHELF_RULES } from "../src/lib/blog/shelves";

const posts = JSON.parse(readFileSync("src/content/blog/catalog.generated.json", "utf8")) as {
  slug: string; title: string; category?: string; keywords?: string;
}[];
const esc = (s: string) => `"${String(s ?? "").replace(/"/g, '""')}"`;
const rows = ["shelf,slug,url,title,catalog_category,reason"];
const counts: Record<string, number> = {};
const more: string[] = [];
for (const p of [...posts].sort((a, b) => a.slug.localeCompare(b.slug))) {
  const m = assignShelf(p);
  counts[m.shelf] = (counts[m.shelf] ?? 0) + 1;
  if (m.shelf === "more") more.push(`- [${p.title}](/blog/${p.slug}) — ${p.category ?? ""}`);
  rows.push([m.shelf, p.slug, `/blog/${p.slug}`, esc(p.title), esc(p.category ?? ""), esc(m.reason)].join(","));
}
writeFileSync("docs/blog/topic-shelves-assignments.csv", rows.join("\n") + "\n");
const md = `# Blog topic shelves — mapping

Generated by \`bun scripts/generate-blog-shelves-mapping.ts\` from \`src/content/blog/catalog.generated.json\`.
Logic lives in \`src/lib/blog/shelves.ts\`. Presentation only: no URLs, titles, meta, canonicals or post structured data change.

## Rules (first match wins)

1. **Supplements** if slug/title/keywords contain: ${SHELF_RULES[0].keywords.join(", ")}.
2. Otherwise by catalog category: ${SHELF_RULES.filter((r) => r.categories.length).map((r) => `${r.label} ← ${r.categories.join(" / ")}`).join("; ")}.
3. Otherwise by keyword: ${SHELF_RULES.slice(1, 5).map((r) => `${r.label} ← ${r.keywords.join(", ")}`).join("; ")}.
4. Otherwise **More guides**.

## Counts (${posts.length} posts)

${SHELF_DISPLAY_ORDER.map((id) => `- ${SHELVES_BY_ID[id].label}: ${counts[id] ?? 0}`).join("\n")}

Full per-post list: [topic-shelves-assignments.csv](./topic-shelves-assignments.csv)

## More guides (${more.length})

${more.join("\n")}
`;
writeFileSync("docs/blog/topic-shelves-mapping.md", md);
console.log(counts);
