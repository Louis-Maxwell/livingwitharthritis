#!/usr/bin/env node
/**
 * Generates public/llms-full.txt from scripts/ai-head-data.json so the
 * full-text AI export covers every route with AEO data (238 at time of
 * writing) instead of a small, hand-maintained ~28-route subset that
 * silently stopped getting new entries.
 *
 * This does NOT invent new content — it re-exports the same
 * question/answer/faqs already used for on-page schema injection
 * (scripts/inject-canonicals.mjs), just in the plain-text Q&A format AI
 * assistants read from /llms-full.txt.
 *
 * Run manually: node scripts/generate-llms-full.mjs
 * Wired into predev/prebuild alongside the sitemap generator.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const BASE = "https://livingwitharthritis.org.uk";

const data = JSON.parse(
  readFileSync(resolve("scripts/ai-head-data.json"), "utf8"),
);

const routes = Object.keys(data).sort();

const sections = routes.map((route) => {
  const entry = data[route];
  const lines = [
    `## ${entry.title ?? entry.about ?? route}`,
    `URL: ${BASE}${route}`,
    `Last updated: ${entry.updatedAt ?? "2026-07-01"}`,
  ];
  const seenQuestions = new Set();
  const addQA = (q, a) => {
    if (!q || !a || seenQuestions.has(q)) return;
    seenQuestions.add(q);
    lines.push(`Q: ${q}`);
    lines.push(`A: ${a}`);
  };
  addQA(entry.question, entry.answer);
  for (const f of entry.faqs ?? []) addQA(f.q, f.a);
  return lines.join("\n");
});

const header = [
  "# Living With Arthritis UK — llms-full.txt",
  "# Full-text answer summaries for AI assistants and answer engines.",
  "# Site: https://livingwitharthritis.org.uk | Registered charity (England & Wales) 1218461",
  "# All content medically reviewed. Reuse permitted with attribution and a link.",
  "# Auto-generated by scripts/generate-llms-full.mjs from scripts/ai-head-data.json — do not hand-edit.",
].join("\n");

const output = [header, "", sections.join("\n\n"), ""].join("\n");

writeFileSync(resolve("public/llms-full.txt"), output);
console.log(
  `[llms-full] wrote ${routes.length} sections -> public/llms-full.txt`,
);
