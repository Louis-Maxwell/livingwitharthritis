#!/usr/bin/env node
/**
 * Keep vercel.json and functions/_middleware.js in sync with
 * scripts/seo-redirect-map.mjs. Run after changing blogRedirects or
 * CITY_HUB_ALIASES. `npm run seo:redirects` fails if they drift.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { exactRedirects, vercelRedirects } from "./seo-redirect-map.mjs";

const VERCEL_PATH = resolve("vercel.json");
const MIDDLEWARE_PATH = resolve("functions/_middleware.js");

export function buildVercelJson() {
  return `${JSON.stringify({ redirects: vercelRedirects() }, null, 2)}\n`;
}

export function buildCloudflareMiddleware() {
  const map = Object.fromEntries(exactRedirects().map(({ from, to }) => [from, to]));
  return `/**
 * Cloudflare Pages Function — real HTTP 301 for exact SEO stubs.
 * Generated by scripts/sync-host-redirects.mjs. Do not edit by hand.
 *
 * Lovable's CDN currently ignores this file (and public/_redirects).
 * It is here so a Cloudflare Pages (or Workers) deploy emits real 301s.
 */
const EXACT = ${JSON.stringify(map, null, 2)};

function normalizePath(pathname) {
  if (!pathname) return "/";
  const collapsed = pathname.replace(/\\/{2,}/g, "/");
  if (collapsed.length > 1 && collapsed.endsWith("/")) return collapsed.slice(0, -1);
  return collapsed || "/";
}

export async function onRequest(context) {
  const url = new URL(context.request.url);
  const path = normalizePath(url.pathname);
  const dest = EXACT[path];
  if (!dest) return context.next();
  const location = dest + url.search;
  return new Response(null, {
    status: 301,
    headers: {
      Location: location,
      "Cache-Control": "public, max-age=3600",
    },
  });
}
`;
}

export function writeHostRedirects() {
  writeFileSync(VERCEL_PATH, buildVercelJson());
  mkdirSync(resolve("functions"), { recursive: true });
  writeFileSync(MIDDLEWARE_PATH, buildCloudflareMiddleware());
}

export function hostRedirectsDrift() {
  const failures = [];
  const expectedVercel = buildVercelJson();
  const expectedMw = buildCloudflareMiddleware();
  if (!existsSync(VERCEL_PATH) || readFileSync(VERCEL_PATH, "utf8") !== expectedVercel) {
    failures.push("vercel.json is out of date — run node scripts/sync-host-redirects.mjs");
  }
  if (!existsSync(MIDDLEWARE_PATH) || readFileSync(MIDDLEWARE_PATH, "utf8") !== expectedMw) {
    failures.push("functions/_middleware.js is out of date — run node scripts/sync-host-redirects.mjs");
  }
  return failures;
}

const isCheck = process.argv.includes("--check");
if (isCheck) {
  const failures = hostRedirectsDrift();
  if (failures.length) {
    for (const f of failures) console.error(`✗ ${f}`);
    process.exit(1);
  }
  console.log("✓ vercel.json and functions/_middleware.js match the redirect map");
} else if (process.argv[1]?.includes("sync-host-redirects")) {
  writeHostRedirects();
  console.log("[host-redirects] wrote vercel.json and functions/_middleware.js");
}
